#if defined COMMONCPP
/// guard class to simplify locking for multithreading
class SimpleGuard {

  ost::Mutex* m_lock;

  public:
    explicit SimpleGuard(ost::Mutex& lock):m_lock(&lock)
    {

      m_lock->enterMutex();

    }

    ~SimpleGuard(void) {

      m_lock->leaveMutex();

     }
};
#endif //COMMONCPP


/// Multithreading data store and exchange structure.
template<class T> class TQueue {

#ifdef COMMONCPP
  ost:: Mutex lock;
#endif //COMMONCPP

  std::deque<T> data;

public:

  /// Constructor
  TQueue() {};

  bool empty(void) {return data.empty();};

  /// put item in queue
  void put(T item) {

    #if defined COMMONCPP
      SimpleGuard g(lock);
    #endif //COMMONCPP

    data.push_back(item);
   
  }


  /// get item from queue
  T get() {

    #if defined  COMMONCPP
      SimpleGuard g(lock);
    #endif //COMMONCPP

    #ifdef EXTRA_OUTPUT
      flush(std::cout << "TQueue::get()=> after mutex locking!" << std::endl);
    #endif //EXTRA_OUTPUT

    if (data.empty() != true) {
      T returnVal;
      returnVal = data.front();
      data.pop_front();
      return returnVal;
    } else {
      T returnVal;
      return returnVal;
    }

  }

};



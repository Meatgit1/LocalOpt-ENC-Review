//------------------------------------------------------------------------------
inline void CEA::pushNc(CNC* nc)
{
  if (nc != 0) 
  {
    m_nc.push_back(nc);
  }
  else Warning("CEA::addNC(CNC* nc): nc pointer = 0!\n");
} // void pushNc(CNC* nc)

//------------------------------------------------------------------------------
inline CNC* CEA::popNc(void)
{
  CNC* nc(0);
  if (m_nc.empty() != true)
  {
    nc = m_nc.back();
    m_nc.pop_back();
  }
  return nc;
} // CNC* popNc(void)


//------------------------------------------------------------------------------
inline CNC* CEA::getNc(const uint i)
{
  CNC* nc(0);
  if ( (m_nc.empty() != true) && (i<m_nc.size()) && (i>=0) ) nc = m_nc[i];
  return nc;
} // CNC* getNc(const uint i)


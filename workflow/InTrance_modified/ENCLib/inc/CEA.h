/// event types that can be signaled by the evolutinary algorithm
enum EAEvent
{
   NOEVENT                                ///< no useful event (shouldn't occur)
  ,SUCCESSFUL_EPOCH                       ///< epoch yield a new best individual
  ,UNSUCCESSFUL_EPOCH      ///< finished epoch did not breed a better individual
  ,LAST_UNSUCCESSFUL_EPOCH       ///< hypercube size change after last bad epoch
  ,SUCCESSFUL_SSS                  ///< new best individual in search space scan
  ,UNSUCCESSFUL_SSS             ///< no new best individual in search space scan
  ,HYPERCUBE_SIZE_CHANGE        ///< the search space hypercube has been changed
  ,NEW_POPULATION_INITIALIZED         ///< a new population has been initialized
};

/*! \brief handler function called upon different events
 *
 * This type definition may be used to provide application-specific
 * handling of events generated by the evolutionary algorithm while
 * it tries to search for and to refine solutions from the given hyperspace
 * which fit best to the given problem.
 *
 * \param event type of occured event
 * \sa getEventHandler, setEventHandler, callEventHandler, EAEvent*/
typedef void (*EaEventHandler) (const EAEvent ea_event);

/*! \brief Interface of user provided handler if hypercube is to be changed due
 * to new epoch.
 *
 *  \param hc_init_size Initial hypercube size
 *  \param hc_curr_size Current hypercube size
 *  \param hc_min_size Minimum hypercube size
 */
typedef void (*NewHcSizeHandler) (
   double hc_init_size
 , double hc_curr_size
 , double hc_min_size);

/// print current settings of evolutionary algorithm
void PrintEaSettings(const CEA* ea);


/// evolutionary algorithm class
class CEA
{
  friend void PrintEaSettings(const CEA* ea);
  friend class CPopulation;
  friend class CIndividual;
  friend class CChromosome;
  friend class CEAOperator;

  std::string m_rep;                                       ///< report file name

  CInputEA m_data;                                       ///< configuration data

  CEAEvalFunc* m_evalfunc;       ///< evolutionary algorithm evaluation function

  CPopulation* m_population;                              ///< population object

  double m_pop_conv_fbc_not_met; ///< population convergence limit (FBC not met)

  double m_pop_conv_fbc_met;         ///< population convergence limit (FBC met)

  double m_final_bound_cond_met_limit;

  // Relative improvement limit (from final population fitness over initial
  // population best individual fitness) if FBC are met by best inidividual of
  // initial population. If this relative improvement is below this boundary
  // the evolutionary algorithm declares convergence and stops.
  double m_epoch_conv_limit_final_bound_cond_met;

  /// improvement limit from two subsequent epochs if
  /// final boundary conditions are not met.
  double m_epoch_conv_limit_final_bound_cond_not_met;

  CEAOperator* m_operator;                     ///< evolutionary operator object

  CIndividual m_partial_solution;            //< pointer to the partial solution
  double m_partial_solution_fitness;        ///< fitness of the partial solution

  CIndividual m_best_individual_epoch;       ///< best individual found in epoch
  double m_best_individual_epoch_fitness;   ///< best epoch individual's fitness

  CIndividual m_best_individual_ever;          ///< best individual found so far
  double m_best_individual_ever_fitness;    ///< fitness of best individual ever

  bool m_avg_fitness_convergence;

  // general problem parameters

  long m_reproduction;                     ///< current # of epoch reproductions
  long m_sss_epoch;                    ///< current # of search space scan epoch
  long m_epoch;                                          ///< current # of epoch

  // delta coding parameters
  double m_delta;              ///< current size of the hypercube to be searched
  double m_delta_factor;
  double m_delta_best;                    ///< size of best solution's hypercube

  /// stop flags; set from extern; primarly for multithreading purose
  bool* m_should_stop;
  ENCObservation::Observer* m_observer; // Optional passive count-bank instrumentation.
  // Fixed isolated checkpoint smoke; never used as a simulation/user-abort flag.
  bool m_preparation_smoke_enabled;
  bool m_preparation_stop;
  unsigned long m_preparation_search_calls;
  unsigned long m_preparation_pairs;
  bool m_ea_converged;                                  ///< EA convergence flag
  int  m_n_bad_epochs;                        ///< number of unsuccessful epochs

  double m_trigger_avg_fitness_ratio;

  bool m_dynamic_mutation_rate;

  /// status data object (for remote purposes)
  EAStatusRec* m_status;

  std::vector<CNC*> m_nc;                           ///< neurocontroller objects

  /// pointer to problem-specific reproduction print function
  PrintReproductionFunction m_print_reproduction;

  /// pointer to problem-specific data structure
  void* m_print_repro_data;

  /// pointer to event handler function
  EaEventHandler m_event_handler;

  /// user provided handler funtion for hypercube change
  NewHcSizeHandler m_new_hc_size_handler;

  KeyboardHandler  m_keyboard_handler;

  /// set counter of unsuccessful epochs to zero
  void resetBadEpochsCounter(void) throw();

  /// decrease counter of unsuccessful epochs by one
  void incBadEpochsCounter(void) throw();

  /// admin postprocessing after a successful epoch
  void goodEpochPostprocess(void) throw();

  /// admin postprocessing after a unsuccessful epoch
  void badEpochPostprocess(void) throw();

  /// admin postprocessing after last unsuccessful epoch
  void lastBadEpochPostprocess(void) throw();

  /*!
   * \brief Output of given message through global output object and report file.
   * The report file output will only be done, when a valid file name has been
   * given to CEA object on construction.
   * \param mess text message to be put out
   */
  void statusMessage(const std::ostringstream& mess);

  /* \brief private helper function to help with checking for zero pointer
   * \sa getEventHandler, setEventHandler, callEventHandler
   * \sa EAEvent, EaEventHandler*/
  void callEventHandler(const EAEvent ea_event) throw();

public:

  void enableObserver(const std::string& filename, unsigned long seed);
  bool observerEnabled(void) const { return m_observer!=0; }
  bool observerStopped(void) const;
  bool reserveObserverGroup(unsigned long count);
  void recordObserverEvaluation(void);
  void recordObserverBoundary(bool population);
  void finishObserver(void);

  // This is a fixed 40 + 2 checkpoint-mechanics probe, not a general budget API.
  void enablePreparationSmoke(void);
  bool preparationSmokeEnabled(void) const throw() { return m_preparation_smoke_enabled; }
  bool preparationStopRequested(void) const throw() { return m_preparation_stop; }
  unsigned long preparationSearchCalls(void) const throw() { return m_preparation_search_calls; }
  unsigned long preparationPairs(void) const throw() { return m_preparation_pairs; }
  void checkPreparationPopulation(void) const;
  void checkPreparationReproduceEntry(void) const;
  void recordPreparationSearchCall(void);
  void recordPreparationPair(void);
  void requestPreparationStop(void);

  const double getCurrentHypercubeSize(void) const throw();

  const CIndividual* getBestSolutionEver(void) const throw();

  /// individual evaluation function
  CEAEvalFunc* getEvalFunc(void) throw();

  /// currently used population
  CPopulation* getCurrentPopulationObject(void) throw();

  /// spread allele values of all population members at given chromosome loci
  /// uniformly
  void uniformSpreadSolutionAlleles(
    const unsigned int loci, const double l_b, const double u_b);

  /*! \brief EA convergence limit in case of not fulfilled boundary conditions 
   * at epoch start
   *\param limit new convergence limit (if omitted, the value already set will
   be returned
   * \return new value (limit >= 0.0) or stored value (limit < 0.0)*/
  double popConvergenceLimitFbcNotMet(const double limit = -1.0) throw();

  /// return limit of hypercube size which is set to be still too big
  double getHypercubeHighLimit(void) const throw();

  /// set hypercube still big limit
  void setHypercubeHighLimit(const double value) throw();

  /// get chromosome loci count
  int getChromosomeLength(void) const throw();

  /// set chromosome loci count
  void setChromosomeLength(const int value) throw();

  /// initial size of search space hypercube
  double getHypercubeInitialSize(void) const throw();

  /// get hypercube shrink factor
  double getHypercubeShrinkFactor(void) const throw();

  /// hypercube start size
  double getHypercubeStartSize(void) throw();

  /// set start size of search space hypercube
  void setHypercubeStartSize(const double val) throw();

  /// set hypercube shrink factor
  void setHypercubeShrinkFactor(const double factor) throw();

  /// increase shrink factor of search space hypercube 
  void incHypercubeShrinkFactor(const double val) throw();

  /// decrease shrink factor of search space hypercube
  void decHypercubeShrinkFactor(const double val) throw();

  void printHypercubeShrinkFactorSetting(const int column_width) const throw();

  /// search space hypercube size modification after bad epoch reproduction
  double getHypercubeModFactorOnBadEpochRepro(void) const throw();

  /// search space hypercube size modification after good epoch reproduction
  double getHypercubeModFactorOnGoodEpochRepro(void) const throw();

  /// get chromosome mutation rate
  double getChromMutationRate(void) const throw();

  /// set chromosome mutation rate
  void setChromMutationRate(const double rate) throw();

  /// get chromosome mutation rate
  double getGenMutationRate(void) const throw();

  /// new set chromosome mutation rate
  void setGenMutationRate(const double rate) throw();

  /// increase mutation rate by given value
  void incChromMutationRate(const double val) throw();

  /// decrease muation rate by given value
  void decChromMutationRate(const double val) throw();

  /// print current mutation rate setting
  void printMutationRateSetting(const int column_width) const throw();

  /// get actual setting of time selection pressure
  double getTimeSelectionPressure(void) const throw();

  /// set new setting for time selection pressure
  void setTimeSelectionPressure(const double pressure) throw();

  // used vector norm
  VectorNorm getVectorNorm(void) const throw();

  // set vector norm to use
  void setVectorNorm(const VectorNorm norm) throw();

  /// returns current count of bad epochs
  int getBadEpochsCount(void) const throw();

  void printBadEpochsStatus(
    const int column_width, const bool with_max = false) const throw();

  /*!\brief max. # of unsuccessful epochs before changing hypercube size
   *\return current setting for maximum number of bad epochs*/
  int getMaxBadEpochsCount(void) const throw();

  /// number of search space scan epochs conducted before optimising
  int getMaxSSSEpochsCount(void) const throw();

  /*!\brief set new max. # of unsuccessful epochs before changing hypercube size
   *\param count new value of max. # of unsuccessful epochs*/
  void setMaxBadEpochsCount(const int count) throw();

  void printMaxBadEpochsSetting(const int column_width) const throw();

  void setAvgFitnessConvergence(const bool val) throw();
  
  bool getAvgFitnessConvergence(void) throw();

  void setTriggerAvgFitnessRatio(const double val) throw();

  double getTriggerAvgFitnessRatio(void) throw();

  void setDynamicMutation(const bool val) throw();

  bool getDynamicMutation(void) throw();

  /*! \brief end optimization of current epoch
   *
   * Calls to this method result in ending of current epoch optimization
   * and start of the next one or even of an end of the whole optimization
   * process depending on settings of the convergence parameters.*/
  void abortCurrentEpoch(void) throw();

  /*! \brief set neurocontroller object to use
   *
   * Redesign of ENCLib should deprecate this method. */
  void pushNc(CNC* nc);

  /*! \brief erase neurocontroller object from list of ncs to use
   *
   * Redesign of ENCLib should deprecate this method.*/
  CNC* popNc(void);

  /*! \brief get pointer of neurocontroller i from list of ncs
   *
   * \param i index of nc
   * \return pointer to a neurocontroller object
   * \sa pushNc, popNc*/
  CNC* getNc(const uint i);

  /// sets given status object and fills it with initial data (assert protected)
  void setStatusObject(EAStatusRec* status) throw();

  /// true if a pointer to a status object is stored and false otherwise
  bool hasStatusObject(void) throw();
  
  /// get stored pointer to status object
  EAStatusRec* getStatusObject(void) throw();
  
  /// fill status object with current EA parameter values
  void updateStatusObject(void) throw();

  // __accessors__

  /*! \brief set new EA event handler function
   *
   * Upon certain events while running the evolutionary algorithm this
   * user-provided function is called with the respective event used as
   * function parameter.
   *
   * \param handler pointer to handler function to be set (default = 0)
   * \sa getEventHandler, callEventHandler, EAEvent, EaEventHandler*/
  void setEventHandler(const EaEventHandler handler = 0) throw();

  /*! \brief return user-provided handler function
   *
   * \return stored value of pointer to handler function
   * \sa setEventHandler, callEventHandler, EAEvent, EaEventHandler*/
  EaEventHandler getEventHandler(void) const throw();

  /*! \brief sets new hc size handler function
   * 
   *  The user provided handler function is called every time the hypercube size
   *  is changed either due to a new best fitness/population inidividual or
   * because there have been to unsuccessfull attempts to improve the 
   * individuals fitness.
   *
   *  \param handler pointer to function of type NewEpochHandler
   *  \sa getNewHcSizeHandler
   */
  void setNewHcSizeHandler(const NewHcSizeHandler handler = 0) throw();

  /*! \brief returns new hc size handler function
   *
   * \return pointer to set handler funtion
   * \sa setNewHcSizeHandler
   */
  NewHcSizeHandler getNewHcSizeHandler(void) const throw();

  /// number of individuals in current population
  int getPopulationSize(void) const throw();

  /// set and store keyboard input handler function pointer
  void setKeyboardHandler(const KeyboardHandler handler = 0) throw();

  /// get pointer to handler function for keyboard inputs
  KeyboardHandler getKeyboardHandler(void) const throw();

  /// constructor for an EA working for a CNC object
  CEA( const CInputEA& input_eap
      ,CNC* nc
      ,CEAEvalFunc* evalfunc
      ,const std::string& rep_file
      ,const PrintReproductionFunction PRF
      ,const NewHcSizeHandler new_hc_size_handler
      ,void* p_data
     );

  /// set convergence limits
  void setLimits(
     const double p_pop_conv_fbc_not_met
    ,const double p_pop_conv_fbc_met
    ,const double p_hyp_large_limit
    ,const double p_final_bound_cond_met_limit
    ,const double p_epoch_conv_limit_final_bound_cond_met
    ,const double p_epoch_conv_limit_final_bound_cond_not_met
  );

  /// destructor
  ~CEA();

  /// debug output function
  void dump(std::string file_name);

  /// shrinks search space hypercube by pre-defined factor
  void modifyHypercube(void);

  /// search space scan, run and local fine tuning
  void Optimize(const std::string& filename = "");

  /// scan search space for optimal partial solution to start with
  void SearchSpaceScan(void);

  /// run the evolutionary algorithm
  void Run(void);

  ///save best found solution to file
  void SaveBestSolution(const char* filename);

  /// set pointer to stop indicator variable
  void setStopBoolPointer(bool* stop_pointer) throw();

  /// get pointer to stop indicator variable
  bool* getStopBoolPointer(void) const throw();

}; // end class CEA

